"""
FoodLoop AI - Model Training and Fine-Tuning Script
Fine-tunes ResNet-50 backbone on custom food classification datasets.
"""

import os
import sys
import json
import argparse
import pandas as pd
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))
BASE_DIR = os.path.dirname(CURRENT_DIR)
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from model.architecture import build_model


class FoodPickleDataset(Dataset):
    """
    Dataset loader for pixel dataframe pickled format (as generated by prepare_dataset.py).
    """
    def __init__(self, dataframe, label_to_index, transform=None):
        self.dataframe = dataframe
        self.label_to_index = label_to_index
        self.transform = transform

    def __len__(self):
        return len(self.dataframe)

    def __getitem__(self, idx):
        row = self.dataframe.iloc[idx]
        label = row["label"]
        pixel_values = row[1:].values.reshape((224, 224, 3)).astype("uint8")
        
        # CHW normalization
        tensor = torch.from_numpy(pixel_values).permute(2, 0, 1).float() / 255.0
        mean = torch.tensor([0.485, 0.456, 0.406]).view(3, 1, 1)
        std = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)
        tensor = (tensor - mean) / std

        label_tensor = torch.tensor(self.label_to_index[label], dtype=torch.long)
        return tensor, label_tensor


def train(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Training on device: {device}")

    # Load dataset dataframe
    if not os.path.exists(args.data_pickle):
        raise FileNotFoundError(f"Pickled dataset not found at: {args.data_pickle}. Run prepare_dataset.py first.")

    df = pd.read_pickle(args.data_pickle)
    unique_labels = sorted(df["label"].unique().tolist())
    num_classes = len(unique_labels)
    label_to_index = {label: idx for idx, label in enumerate(unique_labels)}

    # Save metadata
    os.makedirs(os.path.join(BASE_DIR, "config"), exist_ok=True)
    metadata = {
        "labels": unique_labels,
        "label_to_index": label_to_index
    }
    with open(os.path.join(BASE_DIR, "config", "dataset_metadata.json"), "w") as f:
        json.dump(metadata, f, indent=2)

    with open(os.path.join(BASE_DIR, "config", "num_classes.json"), "w") as f:
        json.dump({"num_classes": num_classes}, f, indent=2)

    dataset = FoodPickleDataset(df, label_to_index=label_to_index)
    dataloader = DataLoader(dataset, batch_size=args.batch_size, shuffle=True)

    # Initialize model
    model = build_model(num_classes=num_classes, device=device)
    
    # Freeze backbone if transfer learning
    if args.freeze_backbone:
        for name, param in model.named_parameters():
            if not name.startswith("fc"):
                param.requires_grad = False
        optimizer = torch.optim.Adam(model.fc.parameters(), lr=args.learning_rate)
    else:
        optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)

    criterion = nn.CrossEntropyLoss()

    print(f"Starting training for {args.epochs} epochs with {num_classes} classes...")
    for epoch in range(args.epochs):
        model.train()
        running_loss = 0.0
        correct_predictions = 0
        total_predictions = 0

        for images, labels in dataloader:
            images, labels = images.to(device), labels.to(device)

            optimizer.zero_grad()
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

            running_loss += loss.item() * images.size(0)
            _, predicted = torch.max(outputs, 1)
            correct_predictions += (predicted == labels).sum().item()
            total_predictions += labels.size(0)

        epoch_loss = running_loss / len(dataloader.dataset)
        epoch_acc = correct_predictions / total_predictions
        print(f"Epoch [{epoch+1}/{args.epochs}] - Loss: {epoch_loss:.4f} - Accuracy: {epoch_acc*100:.2f}%")

    # Save fine-tuned checkpoint
    output_path = args.output_weights or os.path.join(BASE_DIR, "model", "fine_tuned_model.pth")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    torch.save(model.state_dict(), output_path)
    print(f"Fine-tuned model successfully saved to: {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="FoodLoop AI Model Training")
    parser.add_argument("--data_pickle", type=str, default="images.pkl", help="Path to images.pkl dataset file")
    parser.add_argument("--epochs", type=int, default=5, help="Number of training epochs")
    parser.add_argument("--batch_size", type=int, default=32, help="Batch size for training")
    parser.add_argument("--learning_rate", type=float, default=0.001, help="Learning rate")
    parser.add_argument("--freeze_backbone", action="store_true", default=True, help="Freeze ResNet backbone")
    parser.add_argument("--output_weights", type=str, default=None, help="Output .pth checkpoint path")
    args = parser.parse_args()

    train(args)
